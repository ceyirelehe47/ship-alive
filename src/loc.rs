pub fn power_net_summary(n: &crate::power::NetworkInfo, l: &Strings) -> String {
    if n.generators == 0 {
        tfmt!(l.fmt_pow_no_gen, dem = n.demand)
    } else if n.demand > n.generation {
        tfmt!(
            l.fmt_pow_deficit,
            gen = n.generation,
            dem = n.demand,
            served = n.served,
            lack = n.demand - n.served
        )
    } else {
        tfmt!(
            l.fmt_pow_headroom,
            gen = n.generation,
            dem = n.demand,
            served = n.served,
            room = n.generation - n.demand
        )
    }
}

