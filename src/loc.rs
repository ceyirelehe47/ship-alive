pub fn atmo_alert_label(a: &crate::atmosphere::AtmoSummary, l: &Strings) -> Option<&'static str> {
    if a.vacuum_cells > 0 || a.low_cells > 0 {
        Some(l.alert_atmo_loss)
    } else if a.low_o2_cells > 0 {
        Some(l.alert_low_o2)
    } else if a.high_co2_cells > 0 {
        Some(l.alert_high_co2)
    } else if a.polluted_cells > 0 {
        Some(l.alert_polluted)
    } else {
        None
    }
}

