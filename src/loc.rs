#[cfg(test)]
mod tests {
    use super::*;

    /// Both languages expose identical `{placeholder}` sets for every
    /// registered format template — a mismatch would panic at runtime the
    /// first time the line renders in that language.
    #[test]
    fn format_placeholders_match_between_languages() {
        for (i, (en, zh)) in format_pairs().iter().enumerate() {
            let mut e = placeholder_set(en);
            let mut z = placeholder_set(zh);
            e.sort();
            z.sort();
            assert_eq!(e, z, "pair #{i}: {en:?} vs {zh:?}");
        }
    }

    fn placeholder_set(s: &str) -> Vec<String> {
        let mut out = Vec::new();
        let bytes = s.as_bytes();
        for (i, b) in bytes.iter().enumerate() {
            if *b == b'{' {
                if let Some(end) = s[i + 1..].find('}') {
                    out.push(s[i + 1..i + 1 + end].to_string());
                }
            }
        }
        out.retain(|p| !p.is_empty());
        out
    }

    #[test]
    fn every_format_pair_registered() {
        // Spot anchor: a couple of known templates must be in the registry.
        let pairs = format_pairs();
        assert!(pairs.contains(&(EN.fmt_hud_stats, ZH.fmt_hud_stats)));
        assert!(pairs.contains(&(EN.fmt_log_claimed, ZH.fmt_log_claimed)));
    }

    #[test]
    fn lang_codes_round_trip() {
        for lang in [Lang::En, Lang::Zh] {
            assert_eq!(Lang::from_code(lang.code()), Some(lang));
        }
        assert_eq!(Lang::from_code("ZH-CN"), Some(Lang::Zh));
        assert_eq!(Lang::from_code("bogus"), None);
        assert_eq!(Lang::En.toggle(), Lang::Zh);
    }

    #[test]
    fn domain_labels_differ_between_languages() {
        assert_ne!(EN.b_wall, ZH.b_wall);
        assert_ne!(EN.room_cargo, ZH.room_cargo);
        assert_eq!(room_label("CARGO HOLD", &ZH), ZH.room_cargo);
        assert_eq!(room_label("UNKNOWN ROOM", &ZH), "UNKNOWN ROOM");
    }
}
