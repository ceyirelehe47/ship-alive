/// Runtime template formatting for the string table: replaces `{key}`
/// placeholders with `Display` values. Rust's `format!` requires literal
/// templates, so localized templates go through this macro instead.
/// Convention: table templates use NAMED placeholders only (verified by the
/// parity test); floats are pre-formatted at the call site when they need
/// fixed precision.
#[macro_export]
macro_rules! tfmt {
    ($t:expr $(, $k:ident = $v:expr)* $(,)?) => {{
        let mut s = $t.to_string();
        $( s = s.replace(concat!("{", stringify!($k), "}"), &$v.to_string()); )*
        s
    }};
}

/// The active UI language. Persisted in `settings.ini` by the settings
/// module; inserted as a resource before any Startup system runs.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default, Resource)]
pub enum Lang {
    #[default]
    En,
    Zh,
}

impl Lang {
    /// Lower-case code used in the settings file.
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Zh => "zh",
        }
    }

    /// Name of the language in itself (settings buttons).
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Zh => "中文",
        }
    }

    pub fn from_code(code: &str) -> Option<Lang> {
        match code.trim().to_ascii_lowercase().as_str() {
            "en" | "english" => Some(Lang::En),
            "zh" | "cn" | "chinese" | "zh-cn" | "zh_cn" => Some(Lang::Zh),
            _ => None,
        }
    }

    pub fn toggle(self) -> Lang {
        match self {
            Lang::En => Lang::Zh,
            Lang::Zh => Lang::En,
        }
    }
}

