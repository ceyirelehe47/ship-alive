//! Localization (Slice 8): the language resource, the bilingual string
//! table and localized accessors for the domain enums.
//!
//! English stays the canonical/console language — `autotest` dumps and test
//! assertions keep their baselines via the existing English `label()`
//! methods. Every player-facing surface (HUD, panels, tooltips, room
//! annotations, event log) goes through this table instead.
//!
//! The table is two `const` structs with the same fields, so the compiler
//! forces every key to exist in both languages. Strings used as `format!`
//! templates are prefixed `fmt_` and registered in [`format_pairs`]; a unit
//! test asserts the `{placeholder}` sets match between languages.

use crate::building::BuildingKind;
